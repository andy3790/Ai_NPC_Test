// Isolated mock fixtures. Real user records and paid model calls are never used.
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { chromium } from 'playwright';
import { serve } from '../src/server/main.js';
import { Store } from '../src/core/store.js';
import { exampleSpec } from '../src/shared/example.js';
import { historyFixture } from '../tests/history-fixture.js';

mkdirSync('.cache', { recursive: true });
const root = mkdtempSync(resolve('.cache/history-ui-bulk-'));
const foreignFile = join(root, 'reports/archive/npc-lab.sqlite');
const archive = await historyFixture(foreignFile, 'codex');
const foreign = new Store(foreignFile); foreign.patch('runs', archive.detail.run.id, { name: '일괄 삭제 · 보관본' }); foreign.close();
const server = await serve({ port: 0, mock: true, data: join(root, 'current'), historyWorkspace: root });
const spec = exampleSpec('mock-model'); spec.variants = [spec.variants[0]]; spec.repetitions = 3;
const { runs } = await server.engine.create(spec, false);
const [candidate, survivor, active] = runs;
server.engine.store.patch('runs', candidate.id, { name: '일괄 삭제 · 첫번째' });
server.engine.store.patch('runs', survivor.id, { name: '남길 묶음' });
server.engine.store.patch('runs', active.id, { name: '일괄 삭제 · 실행 중', status: 'running' });
const browser = await chromium.launch({ headless: true, channel: process.env.NPC_BROWSER_CHANNEL ?? (process.platform === 'win32' ? 'msedge' : undefined), executablePath: process.env.NPC_BROWSER_EXECUTABLE });
const page = await browser.newPage({ baseURL: server.app.listeningOrigin, viewport: { width: 1440, height: 1080 } });
const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
let locked: DatabaseSync | null = null;
try {
  await page.goto(server.app.listeningOrigin);
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 4);
  await page.locator('.record-origin').waitFor();
  const detailBefore = await page.locator('.record-origin').textContent();
  const check = (id: string) => page.locator(`.run-card-shell[data-run-id="${id}"] input[type=checkbox]`);
  const master = page.getByRole('checkbox', { name: '필터 결과 전체 선택', exact: true });
  const selected = async (count: number) => { await page.locator('.run-selection-bar').getByRole('status').getByText(`선택 ${count}개`, { exact: true }).waitFor(); };
  const openDelete = async (count: number) => { await page.getByRole('button', { name: `선택 삭제 (${count}개)`, exact: true }).click(); await page.getByRole('heading', { name: `대화 묶음 ${count}개를 영구 삭제할까요?`, exact: true }).waitFor(); };
  await check(candidate.id).check(); await selected(1);
  assert.equal(await page.locator('.record-origin').textContent(), detailBefore, 'checkbox must not open another run');
  await master.check(); await selected(4);
  await check(candidate.id).uncheck(); await selected(3);
  assert.equal(await master.evaluate(input => (input as HTMLInputElement).indeterminate), true);
  await master.check(); await selected(4);
  await master.uncheck(); await selected(0);
  assert.equal(await page.getByRole('button', { name: '선택 삭제 (0개)', exact: true }).isDisabled(), true);
  const search = page.getByLabel('기록 검색', { exact: true });
  await search.fill('일괄 삭제');
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 3);
  await master.check(); await selected(3);
  await search.fill('보관본'); await selected(1);
  await search.fill(''); await selected(1);
  assert.equal(await check(survivor.id).isChecked(), false);
  assert.equal(await check(candidate.id).isChecked(), false, 'hidden selection must not return when a filter is cleared');
  await page.getByRole('button', { name: '선택 해제', exact: true }).click();
  await search.fill('일괄 삭제'); await master.check(); await selected(3);
  const newSpec = structuredClone(spec); newSpec.repetitions = 1;
  const arriving = (await server.engine.create(newSpec, false)).runs[0];
  server.engine.store.patch('runs', arriving.id, { name: '일괄 삭제 · 새 기록' }); server.engine.emit('change', { runId: arriving.id });
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 4);
  await selected(3); assert.equal(await check(arriving.id).isChecked(), false);
  await openDelete(3);
  await page.locator('.bulk-delete-count').getByText('선택 3개 · 삭제 가능 2개 · 제외 1개', { exact: true }).waitFor();
  assert.equal(await page.locator('.bulk-delete-list > li').count(), 3);
  await page.screenshot({ path: join(root, 'bulk-confirm-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(root, 'bulk-confirm-mobile.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.getByRole('button', { name: '취소', exact: true }).click();
  assert.equal((await (await page.request.get('/api/runs')).json()).length, 5);
  await selected(3);
  await openDelete(3);
  const permanent = page.getByRole('button', { name: '2개 영구 삭제', exact: true });
  await permanent.waitFor();
  locked = new DatabaseSync(foreignFile); locked.exec('BEGIN IMMEDIATE');
  await permanent.click();
  await page.getByRole('heading', { name: '선택한 묶음 삭제 결과', exact: true }).waitFor();
  await page.locator('.bulk-delete-count').getByText('선택 3개 · 삭제 완료 1개 · 제외 1개 · 실패 1개', { exact: true }).waitFor();
  assert.equal(server.engine.store.get('runs', candidate.id), undefined);
  assert.ok(server.engine.store.get('runs', active.id)); assert.ok(server.engine.store.get('runs', survivor.id));
  assert.equal((await page.request.get(`/api/runs/${archive.detail.run.id}`)).status(), 200);
  await page.screenshot({ path: join(root, 'bulk-partial-result.png') });
  locked.exec('ROLLBACK'); locked.close(); locked = null;
  await page.getByRole('button', { name: '닫기', exact: true }).click(); await selected(2);
  await server.engine.stop(active.id);
  await openDelete(2);
  await page.locator('.bulk-delete-count').getByText('선택 2개 · 삭제 가능 2개 · 제외 0개', { exact: true }).waitFor();
  await page.getByRole('button', { name: '2개 영구 삭제', exact: true }).click();
  await page.locator('.alert.success').getByText('선택한 묶음 2개 중 2개를 삭제했습니다.').waitFor();
  await selected(0);
  await search.fill('');
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 2);
  const remaining = await (await page.request.get('/api/runs')).json();
  assert.deepEqual(remaining.map((run: any) => run.id).sort(), [survivor.id, arriving.id].sort());
  const source = new Store(foreignFile);
  try { assert.equal(source.get('runs', archive.detail.run.id), undefined); } finally { source.close(); }
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  assert.deepEqual(errors, []);
  writeFileSync(join(root, 'result.json'), JSON.stringify({ filterSelection: true, newRunsNotAutoSelected: true, cancel: true, counts: true, partialFailure: true, retry: true, preservedUnselected: true, mobile: true, errors }, null, 2));
  console.log(`BULK_DELETE_UI_OK\n${root}`);
} catch (error) {
  await page.screenshot({ path: join(root, 'failure.png') });
  writeFileSync(join(root, 'failure.json'), JSON.stringify({ alerts: await page.locator('.alert').allTextContents(), dialog: await page.locator('.bulk-delete-dialog').allTextContents(), errors }, null, 2));
  throw error;
} finally { if (locked) { locked.exec('ROLLBACK'); locked.close(); } await browser.close(); await server.close(); }
