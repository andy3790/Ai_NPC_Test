// All fixtures and calls use MockAdapter. No API key or paid calls are used.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { serve } from '../src/server/main.js';
import { historyFixture } from '../tests/history-fixture.js';
import { exampleSpec } from '../src/shared/example.js';

mkdirSync('.cache', { recursive: true });
const root = mkdtempSync(resolve('.cache/history-ui-'));
await historyFixture(join(root, 'reports/api/npc-lab.sqlite'), 'openai', 'per_utterance');
const server = await serve({ port: 0, mock: true, data: join(root, 'current'), historyWorkspace: root });
// Written after server startup, using the real CLI runner's directory shape.
const cli = await historyFixture(join(root, '.cache/history-test-codex-cleanup-12345/npc-lab.sqlite'), 'codex');
const spec = exampleSpec('mock-model'); spec.maxUtterances = 1; spec.evaluation.enabled = false; spec.variants = [spec.variants[0]];
await server.engine.create(spec); await server.engine.idle();
const browser = await chromium.launch({ headless: true, channel: process.env.NPC_BROWSER_CHANNEL ?? (process.platform === 'win32' ? 'msedge' : undefined), executablePath: process.env.NPC_BROWSER_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(server.app.listeningOrigin);
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 3);
  await page.getByLabel('실행 경로', { exact: true }).selectOption('codex');
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 1);
  await page.locator('.record-origin').getByText(/Codex CLI · 보관 기록/).waitFor();
  assert.equal(await page.getByRole('button', { name: '재개', exact: true }).count(), 0);
  await page.getByRole('button', { name: '평가 결과', exact: false }).click();
  assert.equal(await page.getByLabel('평가 검토 상태').isDisabled(), true);
  assert.equal(await page.getByLabel('검토 메모').isDisabled(), true);
  await page.getByRole('button', { name: '호출·계측', exact: true }).click();
  await page.locator('tr.clickable').first().click(); await page.getByRole('heading', { name: '입력', exact: true }).waitFor();
  await page.getByRole('button', { name: '비교에 추가', exact: false }).click();
  await page.getByLabel('실행 경로', { exact: true }).selectOption('openai');
  await page.locator('.compare-pickers input').check();
  await page.waitForFunction(() => document.querySelectorAll('.comparison thead th').length === 3);
  await page.getByRole('heading', { name: '모델·추론별 집계' }).waitFor();
  assert.ok((await page.locator('.comparison').textContent())?.includes('OpenAI API'));
  assert.ok((await page.locator('.comparison').textContent())?.includes('Codex CLI'));
  await page.getByRole('button', { name: '대화 실험실', exact: false }).first().click();
  await page.locator('.record-origin').getByText(/OpenAI API · 보관 기록/).waitFor();
  await page.getByRole('button', { name: '호출·계측', exact: true }).click();
  await page.getByLabel('호출 종류 필터').selectOption('receive');
  assert.equal(await page.locator('tr.clickable').count(), 6);
  await page.getByLabel('기록 검색', { exact: true }).fill('없는 이름');
  await page.getByRole('heading', { name: '검색 조건에 맞는 기록이 없습니다.' }).waitFor();
  await page.getByLabel('기록 검색', { exact: true }).fill('reports/api');
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 1);
  await page.getByRole('button', { name: '기록 다시 검색', exact: true }).click();
  await page.locator('.alert.success').getByText('저장 위치를 다시 검색했습니다.').waitFor();
  await page.getByRole('button', { name: '데이터 내보내기', exact: false }).first().click();
  const ready = page.waitForEvent('download'); await page.getByRole('link', { name: 'ZIP' }).click();
  await (await ready).saveAs(join(root, 'api-export.zip'));
  await page.getByLabel('기록 검색', { exact: true }).fill('');
  await page.getByLabel('실행 경로', { exact: true }).selectOption('all');
  await page.getByRole('button', { name: '대화 실험실', exact: false }).first().click();
  await page.screenshot({ path: join(root, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(root, 'mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  const apiDetail = await page.request.get(`${server.app.listeningOrigin}/api/runs/${cli.detail.run.id}`);
  assert.equal((await apiDetail.json()).summary.speechCount, 3);
  // A separate evaluator finishes while this page remains open.
  await historyFixture(join(root, '.cache/character-performance/late/npc-lab.sqlite'), 'openai');
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 4, undefined, { timeout: 60_000 });
  await page.getByLabel('기록 검색', { exact: true }).fill('character-performance/late');
  await page.waitForFunction(() => document.querySelectorAll('.run-card').length === 1);
  assert.deepEqual(errors, []);
  console.log(`HISTORY_UI_OK: filters, stored dialogues, read-only review, mixed-provider comparison, raw calls, search, refresh, ZIP, mobile\n${root}`);
} finally { await browser.close(); await server.close(); }
